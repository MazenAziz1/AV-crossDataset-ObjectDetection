def table_class_wise_degradation() -> None:
    src = (
        ROOT
        / "outputs"
        / "milestone_6"
        / "generalization_analysis"
        / "tables"
        / "class_wise_degradation.csv"
    )
    df = pd.read_csv(src)
    lines = begin_table(
        "Class-wise cross-dataset degradation in AP@0.50:0.95.",
        "tab:class_wise_degradation",
        "llcccc",
    )
    lines.append(
        "        Detector & Class & KITTI AP & Waymo AP & Abs. drop & Drop (\\%) \\\\"
    )
    lines.append("        \\midrule")
    for det in DETECTOR_ORDER:
        sub = df[df["detector"] == det]
        display = DISPLAY[det]
        for cls in ["Vehicle", "Pedestrian", "Cyclist"]:
            row = sub[sub["class_name"] == cls].iloc[0]
            first = display if cls == "Vehicle" else ""
            lines.append(
                "        "
                + " & ".join(
                    [
                        first,
                        cls,
                        fmt3(row["KITTI_AP50_95"]),
                        fmt3(row["Waymo_AP50_95"]),
                        fmt3(row["absolute_drop"]),
                        fmt2(row["drop_percent"]),
                    ]
                )
                + r" \\"
            )
        lines.append("        \\addlinespace")
    # remove trailing addlinespace
    if lines[-1].strip() == r"\addlinespace":
        lines.pop()
    lines += end_table()
    write_table("tab_class_wise_degradation.tex", lines)


