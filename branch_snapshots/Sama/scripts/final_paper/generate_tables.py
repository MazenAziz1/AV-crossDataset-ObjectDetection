def table_safety_fn() -> None:
    src = ROOT / "outputs" / "milestone_7" / "safety_error_analysis" / "safety_false_negative_summary.csv"
    df = pd.read_csv(src)
    df = df[df["class_name"] == "pedestrian+cyclist"]
    agg = (
        df.groupby(["dataset", "detector"])
        .agg(tp=("tp", "sum"), fn=("fn", "sum"))
        .reset_index()
    )
    agg["fn_rate"] = agg["fn"] / (agg["tp"] + agg["fn"])
    rows = []
    for det in DETECTOR_ORDER:
        record = {"detector": DISPLAY[det]}
        for ds in ["kitti", "waymo"]:
            sub = agg[(agg["detector"] == det) & (agg["dataset"] == ds)]
            record[f"{ds}_fn_rate"] = float(sub["fn_rate"].iloc[0])
        rows.append(record)
    frame = pd.DataFrame(rows)
    lines = begin_table(
        "Safety-critical false-negative rate for pedestrians and cyclists "
        "(operating point, confidence $\\geq 0.25$, IoU $\\geq 0.50$).",
        "tab:safety_fn",
        "lcc",
    )
    lines.append("        Detector & KITTI FN rate & Waymo FN rate \\\\")
    lines.append("        \\midrule")
    for _, r in frame.iterrows():
        lines.append(
            "        "
            + " & ".join(
                [
                    r["detector"],
                    fmt3(r["kitti_fn_rate"]),
                    fmt3(r["waymo_fn_rate"]),
                ]
            )
            + r" \\"
        )
    lines += end_table()
    write_table("tab_safety_fn.tex", lines)


def table_failure_type() -> None:
    src = ROOT / "outputs" / "milestone_7" / "safety_error_analysis" / "failure_type_summary.csv"
    df = pd.read_csv(src)
    cols = [
        ("true_positive", "TP"),
        ("false_negative", "Miss (FN)"),
        ("false_positive", "FP"),
        ("localization_error", "Localization"),
        ("class_confusion", "Confusion"),
        ("over_detection", "Over-detect."),
    ]
    header = ["Dataset", "Detector"] + [c[1] for c in cols]
    lines = begin_table(
        "Failure-type decomposition at the operating point for KITTI and Waymo.",
        "tab:failure_type",
        "l" + "l" + "c" * len(cols),
    )
    lines.append("        " + " & ".join(header) + r" \\")
    lines.append("        \\midrule")
    for ds in ["kitti", "waymo"]:
        ds_label = "KITTI" if ds == "kitti" else "Waymo"
        sub = df[df["dataset"] == ds]
        for det in DETECTOR_ORDER:
            r = sub[sub["detector"] == det].iloc[0]
            first = ds_label if det == DETECTOR_ORDER[0] else ""
            cells = [first, DISPLAY[det]] + [fmt_int(r[c[0]]) for c in cols]
            lines.append("        " + " & ".join(cells) + r" \\")
        lines.append("        \\addlinespace")
    if lines[-1].strip() == r"\addlinespace":
        lines.pop()
    lines += end_table()
    write_table("tab_failure_type.tex", lines)


