def table_dataset_comparison() -> None:
    src = ROOT / "docs" / "milestone_2" / "dataset_comparison_table.csv"
    df = pd.read_csv(src)
    df = df.set_index("metric")
    keep = [
        "Experimental role",
        "Source split",
        "Images",
        "Driving segments",
        "Target boxes",
        "Vehicle boxes",
        "Pedestrian boxes",
        "Cyclist boxes",
        "Images with no target boxes",
        "Camera",
        "Sampling rule",
        "Random seed",
    ]
    header = ["Metric", "KITTI (all)", "KITTI train", "KITTI val.", "Waymo ext."]
    cols = ["kitti_all", "kitti_train", "kitti_validation", "waymo_external_validation"]
    lines = begin_table(
        "Dataset composition and experimental roles of the three frozen partitions.",
        "tab:dataset_comparison",
        "lcccc",
    )
    lines.append("        " + " & ".join(header) + r" \\")
    lines.append("        \\midrule")
    for metric in keep:
        row = df.loc[metric]
        cells = [cell(metric)] + [cell(row[c]) for c in cols]
        lines.append("        " + " & ".join(cells) + r" \\")
    lines += end_table()
    write_table("tab_dataset_comparison.tex", lines)


def table_class_mapping() -> None:
    src = ROOT / "docs" / "milestone_2" / "class_mapping_table.csv"
    df = pd.read_csv(src)
    lines = begin_table(
        "Class harmonization mapping KITTI and Waymo annotations into the common "
        "Vehicle, Pedestrian, and Cyclist task.",
        "tab:class_mapping",
        "llll",
    )
    lines.append("        Dataset & Source class & Action & Unified class \\\\")
    lines.append("        \\midrule")
    for _, r in df.iterrows():
        ds = tex_escape(r["source_dataset"])
        sc = tex_escape(r["source_class_name"])
        action = tex_escape(r["action"])
        uc = tex_escape(r["unified_class_name"]) if pd.notna(r["unified_class_name"]) else "---"
        lines.append(f"        {ds} & {sc} & {action} & {uc} \\\\")
    lines += end_table()
    write_table("tab_class_mapping.tex", lines)


