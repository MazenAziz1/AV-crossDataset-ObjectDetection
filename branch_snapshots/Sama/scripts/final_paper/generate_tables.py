def _size_recall_frame() -> pd.DataFrame:
    src = ROOT / "outputs" / "milestone_7" / "object_size_analysis" / "object_size_summary.csv"
    df = pd.read_csv(src)
    df = df[df["class_name"] == "all"]
    rows = []
    for det in DETECTOR_ORDER:
        record = {"detector": DISPLAY[det]}
        for ds in ["kitti", "waymo"]:
            for sz in ["small", "medium", "large"]:
                sub = df[(df["detector"] == det) & (df["dataset"] == ds) & (df["size_category"] == sz)]
                record[f"{ds}_{sz}"] = float(sub["recall"].iloc[0])
        rows.append(record)
    return pd.DataFrame(rows)


