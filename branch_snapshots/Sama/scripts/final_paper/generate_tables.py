"""Generate the paper-ready LaTeX tables for ``docs/final_paper``.

This script is the *only* place that converts validated project artifacts
(CSV/JSON files under ``outputs/`` and ``docs/``) into the LaTeX tables used by
the paper.  No numerical result is hard-coded here: every cell is read from a
validated source artifact, so that if an underlying result changes the tables
can be regenerated by re-running this script.

Sources (see ``docs/final_paper/README.md`` and ``EVIDENCE_MAP.md``):

  * KITTI in-domain metrics   -> outputs/milestone_5/metrics/kitti_validation/*.json
  * KITTI comparison tables   -> outputs/milestone_5/figures/*.csv
  * Waymo external metrics    -> outputs/milestone_6/waymo_external_validation/*.json / tables/*.csv
  * Generalization analysis   -> outputs/milestone_6/generalization_analysis/tables/*.csv
  * Robustness / safety       -> outputs/milestone_7/object_size_analysis/*.csv
                                 outputs/milestone_7/safety_error_analysis/*.csv
                                 outputs/milestone_7/deployment_tradeoff/*.csv
  * Dataset harmonization     -> docs/milestone_2/*.csv

Usage::

    python scripts/final_paper/generate_tables.py

Output: ``docs/final_paper/tables/*.tex`` (one self-contained table per file).
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "final_paper" / "tables"

DETECTOR_ORDER = ["yolo", "rtdetr", "faster_rcnn", "retinanet"]
DISPLAY = {
    "yolo": "YOLOv8s",
    "rtdetr": "RT-DETR-L",
    "faster_rcnn": "Faster R-CNN",
    "retinanet": "RetinaNet",
}
CLASS_DISPLAY = {
    "Vehicle": "Vehicle",
    "Pedestrian": "Pedestrian",
    "Cyclist": "Cyclist",
}


def cell(value) -> str:
    """Render a table cell, mapping missing/empty values to ``---``."""
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "---"
    s = str(value).strip()
    if s == "" or s.lower() == "nan":
        return "---"
    return tex_escape(s)


def tex_escape(value: str) -> str:
    """Escape LaTeX-sensitive characters in a string cell."""
    return (
        str(value)
        .replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("#", r"\#")
        .replace("_", r"\_")
        .replace("$", r"\$")
        .replace("{", r"\{")
        .replace("}", r"\}")
        .replace("~", r"\textasciitilde{}")
        .replace("^", r"\textasciicircum{}")
    )


def fmt3(x) -> str:
    """Format a float to 3 decimal places."""
    try:
        return f"{float(x):.3f}"
    except (TypeError, ValueError):
        return tex_escape(str(x))


def fmt2(x) -> str:
    """Format a float to 2 decimal places."""
    try:
        return f"{float(x):.2f}"
    except (TypeError, ValueError):
        return tex_escape(str(x))


def fmt1(x) -> str:
    """Format a float to 1 decimal place."""
    try:
        return f"{float(x):.1f}"
    except (TypeError, ValueError):
        return tex_escape(str(x))


def fmt_int(x) -> str:
    """Format an integer with thousands separators."""
    try:
        return f"{int(round(float(x))):,}"
    except (TypeError, ValueError):
        return tex_escape(str(x))


def ordered(df: pd.DataFrame, key: str = "detector") -> pd.DataFrame:
    """Reorder a detector-indexed frame into the canonical display order."""
    out = df.copy()
    out[key] = out[key].map(lambda d: d if d in DETECTOR_ORDER else d)
    present = [d for d in DETECTOR_ORDER if d in set(out[key])]
    out[key] = pd.Categorical(out[key], categories=present, ordered=True)
    out = out.sort_values(key).reset_index(drop=True)
    out[key] = out[key].map(DISPLAY).fillna(out[key])
    return out


def begin_table(caption: str, label: str, colspec: str) -> list[str]:
    return [
        "\\begin{table}[t]",
        "    \\centering",
        f"    \\caption{{{caption}}}",
        f"    \\label{{{label}}}",
        f"    \\begin{{tabular}}{{{colspec}}}",
        "        \\toprule",
    ]


def end_table() -> list[str]:
    return [
        "        \\bottomrule",
        "    \\end{tabular}",
        "\\end{table}",
    ]


def write_table(filename: str, lines: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT / filename)


